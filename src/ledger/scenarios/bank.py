"""Frozen scenario banks (§10.1): generated once, admission-filtered, frozen
to JSON, versioned.  scenario_id = SHA256(generator_version || seed).  The
admission rate over the scanned seed range is logged into the bank file.

Two file formats are read.  `freeze_bank` writes an object with
`bank_id`, `generator_version`, `stats` and `scenarios`.  A few banks were
frozen elsewhere as a bare JSON list of scenarios; they are listed in
`SCENARIO_LIST_BANKS` with the generator version every scenario must carry,
and are loaded the same way (both seat orders per scenario).
"""
from __future__ import annotations

import json
from pathlib import Path

from ..core.scenario import Scenario
from .admit import admit
from .generate import GENERATOR_VERSION, generate
from .._paths import DATA_ROOT

REPO_ROOT = DATA_ROOT  # repository root in a checkout; see ledger/_paths.py
BANKS_DIR = REPO_ROOT / "banks"

#: Banks stored as a bare list of scenarios, and the generator version each
#: scenario in them must carry.  `v2-d0` is the default-game bank of the
#: report's ordinary-play Contracting studies: 12 scenarios from the
#: development generator `scenarios.generate_v2` (K=8, B=100, D=24, p=6,
#: p_def=8, pay_cap 12, settle_window 12), frozen in the research harness as
#: `bank_v2d0.json` and copied here byte for byte.
SCENARIO_LIST_BANKS = {"v2-d0": "ledger-gen-v2-dev"}


def build_bank(n_scenarios: int, start_seed: int = 0, max_seeds: int = 100_000):
    """Scan seeds from start_seed until n_scenarios are admitted.  Returns
    (scenarios, stats)."""
    admitted: list[Scenario] = []
    tried = 0
    for seed in range(start_seed, start_seed + max_seeds):
        tried += 1
        sc = generate(seed)
        rep = admit(sc)
        if rep.admitted:
            admitted.append(sc)
            if len(admitted) >= n_scenarios:
                break
    stats = {
        "generator_version": GENERATOR_VERSION,
        "seeds_tried": tried,
        "admitted": len(admitted),
        "admission_rate": len(admitted) / tried if tried else 0.0,
    }
    return admitted, stats


def freeze_bank(name: str, scenarios: list[Scenario], stats: dict) -> Path:
    BANKS_DIR.mkdir(exist_ok=True)
    path = BANKS_DIR / f"{name}.json"
    payload = {
        "bank_id": name,
        "generator_version": GENERATOR_VERSION,
        "stats": stats,
        "scenarios": [sc.to_dict() for sc in scenarios],
    }
    path.write_text(json.dumps(payload, indent=1, sort_keys=True) + "\n",
                    encoding="utf-8", newline="\n")
    return path


def load_bank(name: str) -> list[Scenario]:
    """Load a frozen bank; each scenario is expanded into both seat orders
    (opening mover 1 and 2), giving 2x templates."""
    path = BANKS_DIR / f"{name}.json"
    payload = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(payload, list):
        return _load_scenario_list(name, payload)
    if payload["generator_version"] != GENERATOR_VERSION:
        raise ValueError(
            f"bank {name} was generated by {payload['generator_version']}, "
            f"current is {GENERATOR_VERSION}: refused, not coerced")
    out = []
    for d in payload["scenarios"]:
        sc = Scenario.from_dict(d)
        out.append(sc)
        out.append(sc.with_opening(3 - sc.opening))
    return out


def _load_scenario_list(name: str, payload: list) -> list[Scenario]:
    """A bare-list bank: refused unless registered in SCENARIO_LIST_BANKS and
    every scenario carries the registered generator version.  Expanded into
    both seat orders like `load_bank`, so template 2*i is scenario i as
    stored and template 2*i + 1 is the other seat order."""
    want = SCENARIO_LIST_BANKS.get(name)
    if want is None:
        raise ValueError(f"bank {name} is a bare scenario list but is not "
                         f"registered in SCENARIO_LIST_BANKS: refused")
    out = []
    for d in payload:
        if d["generator_version"] != want:
            raise ValueError(
                f"bank {name} scenario {d['scenario_id'][:12]} was generated "
                f"by {d['generator_version']}, registered is {want}: refused, "
                "not coerced")
        sc = Scenario.from_dict(d)
        out.append(sc)
        out.append(sc.with_opening(3 - sc.opening))
    return out


def bank_stats(name: str) -> dict:
    path = BANKS_DIR / f"{name}.json"
    return json.loads(path.read_text(encoding="utf-8"))["stats"]
